// The engine's key catalog — `engine/authoring/reference/catalog.schema.json`,
// the JSON Schema the engine generates from its parser and its fact tables —
// as a build-time import, and the reads a property panel needs from it.
//
// The catalog is the ENGINE's statement of what each key does: a style key's
// initial value, whether it inherits, the bounds a guard holds a number to,
// which style keys change each item type's output, which values name something
// defined elsewhere, and which capability key gates a node (the `x-shojiku-*`
// keywords, plus `minimum`/`exclusiveMinimum`/`maximum`). Reading it here,
// rather than copying the facts into panel code, is what keeps the two from
// drifting. The file is committed and regenerated by `make reference:generate`,
// so it always matches the engine source this checkout builds.

import document from '../../../engine/authoring/reference/catalog.schema.json';

/** The parts of a catalog node the reads below look at. */
interface CatalogNode {
  readonly 'x-shojiku-initial'?: unknown;
  readonly 'x-shojiku-inherited'?: boolean;
  readonly minimum?: number;
  readonly exclusiveMinimum?: number;
  readonly maximum?: number;
}

/** A node a `style:` is authored on. */
interface StyledNode {
  readonly 'x-shojiku-style-keys'?: readonly string[];
  readonly 'x-shojiku-initial-overrides'?: Readonly<Record<string, unknown>>;
}

/** One `Item` branch: its `type:` discriminator, and what it says about style. */
interface ItemBranch extends StyledNode {
  readonly properties: { readonly type: { readonly const: string } };
}

/** The three shapes the reads use. The engine's own tests hold that the
 * catalog carries each, with these keywords on them. */
interface Catalog {
  readonly $defs: {
    readonly Style: { readonly properties: Readonly<Record<string, CatalogNode>> };
    readonly Item: { readonly oneOf: readonly ItemBranch[] };
    readonly Span: { readonly 'x-shojiku-style-keys': readonly string[] };
  };
}

/** The catalog's shapes. Read inside each function rather than at module
 * scope, so a bundle that calls none of the reads drops the JSON entirely. */
function defs(): Catalog['$defs'] {
  return (document as unknown as Catalog).$defs;
}

/** The `Item` branch for an item `type:`, or `undefined` for an unknown type. */
function itemBranch(type: string): ItemBranch | undefined {
  return defs().Item.oneOf.find((branch) => branch.properties.type.const === type);
}

/** What the engine says about one `Style` key. */
export interface StyleKeyFacts {
  /** The value it takes at the document root when nothing authors it, in its
   * wire form; `undefined` where absence is the value (no fill, no family). */
  readonly initial: unknown;
  readonly inherited: boolean;
  /** The bounds a numeric key is held to (on the resolved pt for a length);
   * a value outside them is replaced by the engine, with a warning. */
  readonly minimum?: number;
  readonly exclusiveMinimum?: number;
  readonly maximum?: number;
}

/** Every `Style` key the engine takes, in the catalog's (alphabetical) order. */
export function styleKeys(): readonly string[] {
  return Object.keys(defs().Style.properties);
}

/** The engine's facts for one `Style` key, or `undefined` for a key it does not
 * take. */
export function styleKeyFacts(key: string): StyleKeyFacts | undefined {
  const { properties } = defs().Style;
  if (!Object.hasOwn(properties, key)) {
    return undefined;
  }
  const node = properties[key];
  return {
    initial: node['x-shojiku-initial'],
    inherited: node['x-shojiku-inherited'] === true,
    minimum: node.minimum,
    exclusiveMinimum: node.exclusiveMinimum,
    maximum: node.maximum,
  };
}

/** The style keys that change what an item of `type` draws — painted by it, or
 * inherited into what it holds — in `Style` field order. Empty for a type that
 * takes no `style:` (a `line` strokes with its own shape) or that the catalog
 * does not know. */
export function itemStyleKeys(type: string): readonly string[] {
  return itemBranch(type)?.['x-shojiku-style-keys'] ?? [];
}

/** The style keys a rich-text span paints with, in `Style` field order. */
export function spanStyleKeys(): readonly string[] {
  return defs().Span['x-shojiku-style-keys'];
}

/** Where an item of `type` starts a style key somewhere other than its root
 * initial value (a form mark's 1 pt outline, a table's middle-aligned cells).
 * A `null` value means the item derives it (a char_grid sizes its glyphs from
 * the cell). */
export function itemInitialOverrides(type: string): Readonly<Record<string, unknown>> {
  return itemBranch(type)?.['x-shojiku-initial-overrides'] ?? {};
}
