// The engine's key catalog — `engine/authoring/reference/catalog.schema.json`,
// the JSON Schema the engine generates from its parser and its fact tables —
// as a build-time import, and the typed view of it the catalog reads share.
//
// The catalog is the ENGINE's statement of what each key does: a style key's
// initial value, whether it inherits, the bounds a guard holds a number to,
// which style keys change each item type's output, which values name something
// defined elsewhere, which capability key gates a node, and what a string or
// number means (a colour, a 0–1 fraction) — the `x-shojiku-*` keywords, plus
// the plain JSON Schema shape. Reading it, rather than copying the facts into
// panel code, is what keeps the two from drifting. The file is committed and
// regenerated by `make reference:generate`, so it always matches the engine
// source this checkout builds.

import document from '../../../../engine/authoring/reference/catalog.schema.json';

/** The parts of a catalog node (a JSON Schema object) the reads look at. */
export interface CatalogNode {
  readonly type?: string | readonly string[];
  readonly enum?: readonly unknown[];
  readonly const?: unknown;
  readonly oneOf?: readonly CatalogNode[];
  readonly anyOf?: readonly CatalogNode[];
  readonly $ref?: string;
  readonly properties?: Readonly<Record<string, CatalogNode>>;
  readonly additionalProperties?: CatalogNode | boolean;
  readonly required?: readonly string[];
  readonly minimum?: number;
  readonly exclusiveMinimum?: number;
  readonly maximum?: number;
  readonly 'x-shojiku-initial'?: unknown;
  readonly 'x-shojiku-inherited'?: boolean;
  readonly 'x-shojiku-capability'?: string;
  readonly 'x-shojiku-ref'?: string;
  readonly 'x-shojiku-value-kind'?: string;
  readonly 'x-shojiku-style-keys'?: readonly string[];
  readonly 'x-shojiku-initial-overrides'?: Readonly<Record<string, unknown>>;
}

/** A node whose keys are listed by name. */
export interface ObjectNode extends CatalogNode {
  readonly properties: Readonly<Record<string, CatalogNode>>;
}

/** One `Item` branch: its `type:` discriminator, and what it says about style. */
export interface ItemBranch extends ObjectNode {
  readonly properties: Readonly<Record<string, CatalogNode>> & {
    readonly type: { readonly const: string };
  };
}

/** The shapes the reads name directly. The engine's own tests hold that the
 * catalog carries each, with these keywords on them. */
interface Defs {
  readonly Style: ObjectNode;
  readonly Item: { readonly oneOf: readonly ItemBranch[] };
  readonly Span: { readonly 'x-shojiku-style-keys': readonly string[] };
  readonly TemplateDefaults: {
    readonly properties: { readonly style: { readonly 'x-shojiku-style-keys': readonly string[] } };
  };
}

/** The catalog's shapes. Read inside each function rather than at module
 * scope, so a bundle that calls none of the reads drops the JSON entirely. */
export function defs(): Defs {
  return (document as unknown as { readonly $defs: Defs }).$defs;
}

/** The `Item` branch for an item `type:`, or `undefined` for an unknown type. */
export function itemBranch(type: string): ItemBranch | undefined {
  return defs().Item.oneOf.find((branch) => branch.properties.type.const === type);
}

const DEFS_PREFIX = '#/$defs/';

/** The `$defs` name a `$ref` points at, or `undefined` for a reference that
 * leaves `$defs` (the catalog writes none). */
export function refName(ref: string): string | undefined {
  return ref.startsWith(DEFS_PREFIX) ? ref.slice(DEFS_PREFIX.length) : undefined;
}

/** The `$defs` node a `$ref` points at, or `undefined` for a name the catalog
 * lacks (including one only an object prototype has). */
export function defNode(ref: string): CatalogNode | undefined {
  const name = refName(ref);
  const all = defs() as unknown as Readonly<Record<string, CatalogNode>>;
  return name !== undefined && Object.hasOwn(all, name) ? all[name] : undefined;
}
